#!/usr/bin/env python3
"""Convert Hyprland 0.53–0.56 `windowrule` / `layerrule` lines (the
`match:prop value, effect value` syntax) into 0.57 Lua.

    gen_rules.py RULES.conf [MORE.conf ...] > rules.lua
"""
import re
import sys

BOOL = {"on": True, "true": True, "1": True, "yes": True, "off": False, "false": False, "0": False, "no": False}
# effects whose value is a plain on/off
FLAGS = {"float", "center", "pin", "no_blur", "no_initial_focus", "keep_aspect_ratio", "blur", "no_anim",
         "fullscreen", "maximize", "tile", "no_shadow", "no_border", "no_dim", "no_focus", "blur_popups", "xray"}
NUMBERS = {"ignore_alpha", "border_size", "rounding", "order"}


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def value(key, v):
    v = v.strip()
    if key in FLAGS and v.lower() in BOOL:
        return "true" if BOOL[v.lower()] else "false"
    if key in NUMBERS and re.fullmatch(r"-?\d+(\.\d+)?", v):
        return v
    return lua_str(v)


def parse_parts(parts):
    match, effects = {}, {}
    for part in parts:
        part = part.strip()
        if not part:
            continue
        # a part may hold several "match:x y" chunks separated by spaces
        for m in re.finditer(r"match:(\w+)\s+(.+?)(?=\s+match:\w+\s|$)", part) if part.startswith("match:") else []:
            match[m.group(1)] = m.group(2).strip()
        if part.startswith("match:"):
            continue
        key, _, val = part.partition(" ")
        effects[key] = val.strip() or "on"
    return match, effects


def emit(kind, match, effects, name=None):
    if not match:
        return None
    # rules that only ever matched everything (e.g. class ^(*)$) are noise
    if any(v in ("^(*)$",) for v in match.values()):
        return None
    lines = [f"hl.{kind}({{"]
    if name:
        lines.append(f"    name = {lua_str(name)},")
    m = ", ".join(f"{k} = {value(k, v) if k == 'fullscreen' else lua_str(v)}" for k, v in match.items())
    lines.append(f"    match = {{ {m} }},")
    for k, v in effects.items():
        lines.append(f"    {k} = {value(k, v)},")
    lines.append("})")
    return "\n".join(lines)


def main():
    out = ["-- Generated by ~/.config/prism/hypr/gen_rules.py from the JaKooLit window rules.",
           "-- Edit the generator or add rules below; regenerate with:",
           "--   gen_rules.py ~/.config/hypr/configs/WindowRules.conf > ~/.config/hypr/rules.lua", ""]
    seen = set()
    for path in sys.argv[1:]:
        text = open(path).read()
        # block rules
        for blk in re.finditer(r"(windowrule|layerrule)\s*\{(.*?)\}", text, re.S):
            kind = "window_rule" if blk.group(1) == "windowrule" else "layer_rule"
            match, effects, name = {}, {}, None
            for line in blk.group(2).splitlines():
                line = re.sub(r"\s#.*", "", line).strip()
                if "=" not in line:
                    continue
                k, v = (s.strip() for s in line.split("=", 1))
                if k == "name":
                    name = v
                elif k.startswith("match:"):
                    match[k[6:]] = v
                else:
                    effects[k] = v
            r = emit(kind, match, effects, name)
            if r and r not in seen:
                seen.add(r)
                out.append(r)
        text = re.sub(r"(windowrule|layerrule)\s*\{.*?\}", "", text, flags=re.S)
        for line in text.splitlines():
            line = re.sub(r"\s#.*", "", line).strip()
            mm = re.match(r"(windowrule|layerrule)\s*=\s*(.+)", line)
            if not mm:
                continue
            kind = "window_rule" if mm.group(1) == "windowrule" else "layer_rule"
            match, effects = parse_parts(mm.group(2).split(","))
            r = emit(kind, match, effects)
            if r and r not in seen:
                seen.add(r)
                out.append(r)
    print("\n".join(out))


if __name__ == "__main__":
    main()
